package com.example.bank.notify;

import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;
import java.util.Optional;

import com.example.bank.notify.NotificationDtos.NotificationDto;
import jakarta.annotation.PostConstruct;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;
import org.springframework.stereotype.Repository;

/**
 * H2 persistence for the notification inbox. The {@code id} column is a monotonic
 * identity cursor — polling never cursors on created_at (equal timestamps would
 * lose events). The unique {@code dedupe_key} makes emission idempotent.
 */
@Repository
public class NotificationStore {

    private static final Logger log = LoggerFactory.getLogger(NotificationStore.class);

    private final JdbcTemplate jdbc;

    public NotificationStore(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @PostConstruct
    void createTable() {
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS notifications (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id VARCHAR(64) NOT NULL,
                    conversation_id VARCHAR(64) NOT NULL,
                    job_id VARCHAR(64),
                    type VARCHAR(32) NOT NULL,
                    title VARCHAR(140) NOT NULL,
                    body VARCHAR(300) NOT NULL,
                    detail CLOB,
                    read_at BIGINT,
                    created_at BIGINT NOT NULL,
                    dedupe_key VARCHAR(160) UNIQUE
                )
                """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_notifications_user_id ON notifications (user_id, id)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_notifications_user_read ON notifications (user_id, read_at)");
    }

    /**
     * Inserts a row and returns its id. Returns {@link Long#MIN_VALUE} when the
     * dedupe key already exists (the caller must then skip message + push).
     */
    public long insert(String userId, String conversationId, String type, String title, String body,
            String detail, String jobId, String dedupeKey, long createdAt) {
        KeyHolder keyHolder = new GeneratedKeyHolder();
        try {
            jdbc.update(connection -> {
                PreparedStatement ps = connection.prepareStatement("""
                        INSERT INTO notifications
                            (user_id, conversation_id, job_id, type, title, body, detail, created_at, dedupe_key)
                        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                        """, Statement.RETURN_GENERATED_KEYS);
                ps.setString(1, userId);
                ps.setString(2, conversationId);
                ps.setString(3, jobId);
                ps.setString(4, type);
                ps.setString(5, clamp(title, 140));
                ps.setString(6, clamp(body, 300));
                ps.setString(7, detail);
                ps.setLong(8, createdAt);
                ps.setString(9, dedupeKey);
                return ps;
            }, keyHolder);
        } catch (DuplicateKeyException ex) {
            log.debug("Duplicate notification dedupe_key {}", dedupeKey);
            return Long.MIN_VALUE;
        }
        Number key = keyHolder.getKey();
        return key == null ? Long.MIN_VALUE : key.longValue();
    }

    public Optional<Long> findIdByDedupeKey(String dedupeKey) {
        if (dedupeKey == null || dedupeKey.isBlank()) {
            return Optional.empty();
        }
        return jdbc.query("SELECT id FROM notifications WHERE dedupe_key = ?",
                (rs, rowNum) -> rs.getLong(1), dedupeKey).stream().findFirst();
    }

    public List<NotificationDto> list(String userId, long sinceId, int limit, boolean unreadOnly) {
        String sql = "SELECT id, user_id, conversation_id, type, title, body, detail, job_id, read_at, created_at "
                + "FROM notifications WHERE user_id = ? AND id > ?"
                + (unreadOnly ? " AND read_at IS NULL" : "")
                + " ORDER BY id ASC LIMIT ?";
        return jdbc.query(sql, (rs, rowNum) -> new NotificationDto(
                rs.getLong("id"),
                rs.getString("user_id"),
                rs.getString("conversation_id"),
                rs.getString("type"),
                rs.getString("title"),
                rs.getString("body"),
                rs.getString("detail"),
                rs.getString("job_id"),
                rs.getObject("read_at") != null,
                rs.getLong("created_at")), userId, sinceId, limit);
    }

    public long unreadCount(String userId) {
        Long count = jdbc.queryForObject("SELECT COUNT(*) FROM notifications WHERE user_id = ? AND read_at IS NULL",
                Long.class, userId);
        return count == null ? 0 : count;
    }

    /** Idempotent: only flips unread rows, so repeated calls do not change read_at. */
    public boolean markRead(long id, String userId, long readAt) {
        return jdbc.update("UPDATE notifications SET read_at = ? WHERE id = ? AND user_id = ? AND read_at IS NULL",
                readAt, id, userId) > 0;
    }

    public int markAllRead(String userId, long readAt) {
        return jdbc.update("UPDATE notifications SET read_at = ? WHERE user_id = ? AND read_at IS NULL",
                readAt, userId);
    }

    public boolean delete(long id, String userId) {
        return jdbc.update("DELETE FROM notifications WHERE id = ? AND user_id = ?", id, userId) > 0;
    }

    public Optional<Long> maxId(String userId) {
        return jdbc.query("SELECT MAX(id) FROM notifications WHERE user_id = ?",
                (rs, rowNum) -> {
                    long value = rs.getLong(1);
                    return rs.wasNull() ? null : value;
                }, userId).stream().findFirst().filter(java.util.Objects::nonNull);
    }

    public boolean existsForUser(long id, String userId) {
        Long count = jdbc.queryForObject("SELECT COUNT(*) FROM notifications WHERE id = ? AND user_id = ?",
                Long.class, id, userId);
        return count != null && count > 0;
    }

    private static String clamp(String value, int max) {
        if (value == null) {
            return "";
        }
        return value.length() > max ? value.substring(0, max) : value;
    }
}
